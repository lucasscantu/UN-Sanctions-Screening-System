package com.sanctions.screening.config;

import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI customOpenAPI() {
        return new OpenAPI()
                .info(new Info()
                        .title("UN Sanctions Screening API")
                        .version("1.0.0")
                        .description("API for screening individuals and entities against the United Nations Security Council Consolidated Sanctions List")
                        .contact(new Contact()
                                .name("Sanctions Screening System")
                                .email("admin@sanctions-screening.local"))
                        .license(new License()
                                .name("Apache 2.0")
                                .url("https://www.apache.org/licenses/LICENSE-2.0")));
    }
}
